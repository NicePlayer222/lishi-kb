CARD_RE = re.compile(r"(##\s*⚡\s*快速知识卡\s*\n)(.*?)(\n##)", re.S)


def cn_len(s):
    return len(re.sub(r"[^\u4e00-\u9fff]", "", s))


def main():
    dry = "--dry-run" in sys.argv
    ok = True
    for name, card in NEW.items():
        path = ROOT / "topics" / f"{name}.md"
        raw = path.read_bytes().decode("utf-8")
        m = CARD_RE.search(raw)
        if not m:
            print(f"[FAIL] {name}: 找不到知识卡小节")
            ok = False
            continue
        old = m.group(2).strip()
        new_body = "\n" + card + "\n"
        n = cn_len(card)
        status = "OK " if 140 <= n <= 260 else "BAD"
        if status == "BAD":
            ok = False
        print(f"{status} {name}: {cn_len(old)} -> {n} 字")
        if dry or status == "BAD":
            continue
        out = raw[: m.start(2)] + new_body + raw[m.end(2):]
        path.write_bytes(out.encode("utf-8"))
    if dry:
        print("[dry-run] 未写入")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
